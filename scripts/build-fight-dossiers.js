#!/usr/bin/env node
/* eslint-env node, es6 */
'use strict';

/**
 * Build the fight-dossier oracle: threat structure and named answers for
 * every fight of the run map, precomputed so runtime pays a dictionary
 * lookup — the advisor, the plan panel and the ranker read this file and
 * never touch the grid machinery in play.
 *
 * Cost model (measured 2026-08-28: 26ms per six-versus-party grid chunk):
 * one shared sample per level-cap stretch, stratified to 48 species for
 * ordinary fights, the full pool for boss-tier fights — ~90 seconds for
 * all 366. The sample for a stretch is built at the stretch's LAST order
 * (its cap boss), so rows early in a stretch may name species that open
 * mid-stretch: consumers that advise catching must re-gate by
 * availability at their own position, which adviseCatches does anyway.
 *
 * Freshness travels as a stamp: the order-scale id plus a digest of every
 * input. tests/fight_dossiers.test.js checks the stamp against the live
 * inputs — cheap, no rebuild — and fails when this file is stale. This is
 * a DECLARED exception to the byte-regeneration gate pattern
 * (trainer-orders.json): a full rebuild is minutes, not milliseconds, so
 * the gate verifies provenance instead of bytes. Regenerate with:
 *
 *   node scripts/build-fight-dossiers.js
 */

const fs = require('node:fs');
const crypto = require('node:crypto');
const planner = require('../lib/planner');
const dossier = require('../lib/dossier');
const encountersProfile = require('../profiles/run-and-bun/encounters.js');

const OUT = 'profiles/run-and-bun/oracle/fight-dossiers.json';
const STRATIFIED_SIZE = 48;
const BOSS = /^(Leader |Elite Four |Champion )/;

const INPUTS = {
	setdex: 'src/js/data/sets/gen8.js',
	learnsets: 'profiles/run-and-bun/oracle/learnsets.json',
	availability: 'profiles/run-and-bun/oracle/availability.json',
	evolutions: 'profiles/run-and-bun/oracle/evolutions.json',
};

function digest(path) {
	return crypto.createHash('sha256').update(fs.readFileSync(path)).digest('hex').slice(0, 16);
}

function main() {
	const started = Date.now();
	const fights = planner.loadRunMap('run-and-bun');

	// One sample per cap stretch, built at the stretch's last order.
	const byCap = new Map();
	for (const row of encountersProfile.LEVEL_CAPS) {
		byCap.set(row.cap, dossier.buildSample(row.order));
	}

	const rows = [];
	for (const fight of fights) {
		const cap = dossier.capOf(fight.order);
		const stretch = byCap.get(cap) || dossier.buildSample(fight.order);
		const boss = BOSS.test(fight.trainer);
		const sample = boss ? stretch.sample :
			dossier.stratify(stretch.sample, STRATIFIED_SIZE);
		rows.push(dossier.dossierFor(fight, cap, sample, boss));
	}

	const out = {
		comment: 'Generated by scripts/build-fight-dossiers.js — threat structure and ' +
			'named answers per fight, priced by the engine matchup grid against the ' +
			'period-catchable sample. Do not edit by hand; the freshness gate reads ' +
			'the stamp, and regeneration is the fix for a stale one.',
		stamp: {
			orderScale: encountersProfile.ORDER_SCALE.id,
			battles: fights.length,
			inputs: Object.fromEntries(Object.entries(INPUTS)
				.map(entry => [entry[0], digest(entry[1])])),
		},
		fights: rows,
	};
	fs.writeFileSync(OUT, JSON.stringify(out, null, '\t') + '\n');
	console.log(rows.length + ' fights -> ' + OUT + ' in ' +
		((Date.now() - started) / 1000).toFixed(0) + 's');
}

main();
