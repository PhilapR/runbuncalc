import {
	createRabRunRuntimeProvider,
	resolveRabTrainerOrder,
} from '@philapr/pokemon-run-runtime';

import trainerOrders from '../../profiles/run-and-bun/oracle/trainer-orders.json' with {type: 'json'};

const metadata = Object.freeze({
	repository: 'pokemon-mono',
	engineRevision: '2ae1b7e5721a2d2ff3b9692df75f65329c891650',
	artifactSha256: '5503927e7d7cccc85bae88f30c4d73a2c4f7c2c207096c0166693fcb8d108e55',
	contractRevision: '8e2c3c8f021094814b1b44844c7de4992095d274',
	contractDigest: '402809acb338a7fc274e72ae9bcc6efbe4956f8a980a951e05b665ee52f0ba75',
});

/**
 * Fight label to engine trainer order.
 *
 * resolveRabTrainerOrder answers only for a label the engine spells exactly as
 * we do, and 152 of this run's 362 fights are spelled differently — almost all
 * because the engine files a DOUBLE under its lead ("School Kid Jerry", partner
 * "Youngster Johnson") where we write both names, and because we disambiguate
 * 24 identically-named Team Aqua grunts by location and it does not. Every one
 * of those fights lost its survival forecast.
 *
 * profiles/run-and-bun/oracle/trainer-orders.json is the reconciliation,
 * generated by scripts/build-trainer-order-map.js from the two pinned
 * databases: the label the engine already resolves where it does, and a match
 * on the TEAM where it does not. It carries 210 of the first and 124 of the
 * second, and none of the 28 fights it could not place.
 */
const ORDER_BY_LABEL = new Map(trainerOrders.entries.map(entry => [entry.trainer, entry.order]));

/**
 * The map first, then the engine.
 *
 * The map already holds every label the engine resolves, so the fallback only
 * runs for a label neither knows — and there it throws the engine's own error,
 * which is the behaviour every caller was written against. A fight the map
 * cannot place still gets no forecast; what it must never get is somebody
 * else's trainer.
 */
function resolveTrainerOrder(trainer) {
	const mapped = ORDER_BY_LABEL.get(trainer);
	if (mapped !== undefined) return mapped;
	return resolveRabTrainerOrder(trainer);
}

globalThis.RunBunPokemonProvider = Object.freeze({
	metadata,
	resolveTrainerOrder,
	trainerOrderMap: Object.freeze({
		profileId: trainerOrders.profileId,
		resolvedByName: trainerOrders.resolvedByName,
		resolvedByTeam: trainerOrders.resolvedByTeam,
		unmatched: trainerOrders.unmatchedCount,
	}),
	provider: createRabRunRuntimeProvider({
		providerRevision: metadata.engineRevision,
		engineVersion: '0.2.0',
	}),
});
